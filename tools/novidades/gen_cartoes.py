#!/usr/bin/env python3
"""Tela de novidades do Prof. Carvalho: gera src/data/novidades_cartoes.h a partir do cartoes.json.

Uso (o make chama sozinho): python3 tools/novidades/gen_cartoes.py <cartoes.json> <saída.h>

O JSON tem `topics[]` (id, name, iconItemId, iconCustom, cards[]) e cada cartão tem title, body e,
opcionalmente, before/after (linha "ANTES: ... / AGORA: ..."), speciesBefore/speciesAfter e itemId,
com os mesmos nomes dos campos de `struct NovidadesCard`/`NovidadesTopic` (include/novidades.h).
Quebras de linha do texto são `\\n` de verdade no JSON e viram `\\n` literal no `_("...")`.

O header é só `const` (nenhum EWRAM_DATA) e é incluído por src/novidades_data.c. Campos vazios
ficam de fora do inicializador (NULL/0).
"""

import json
import re
import sys
from pathlib import Path

TEXT_FIELDS = ("title", "before", "after", "body")
IDENT = re.compile(r"[a-z][a-z0-9_]*")
CONSTANT = {"speciesBefore": re.compile(r"SPECIES_[A-Z0-9_]+"),
            "speciesAfter": re.compile(r"SPECIES_[A-Z0-9_]+"),
            "itemId": re.compile(r"ITEM_[A-Z0-9_]+")}


def _c_string(text: str, where: str) -> str:
    if '"' in text or "\\" in text:
        raise ValueError(f"{where}: aspas e barra invertida não entram no texto do cartão")
    return text.replace("\n", "\\n")


def _check_card(card: dict, where: str) -> None:
    for field in ("title", "body"):
        if not card.get(field):
            raise ValueError(f"{where}: cartão sem {field}")
    if bool(card.get("before")) != bool(card.get("after")):
        raise ValueError(f"{where}: before e after vêm juntos")
    if card.get("speciesAfter") and not card.get("speciesBefore"):
        raise ValueError(f"{where}: speciesAfter sem speciesBefore")
    if card.get("itemId") and card.get("speciesBefore"):
        raise ValueError(f"{where}: a imagem é uma espécie OU um item")
    for field, pattern in CONSTANT.items():
        if card.get(field) and not pattern.fullmatch(card[field]):
            raise ValueError(f"{where}: {field} '{card[field]}' não é uma constante válida")


def render(json_path) -> str:
    data = json.loads(Path(json_path).read_text(encoding="utf-8"))
    out = [
        "//",
        "// DO NOT MODIFY THIS FILE! It is auto-generated by tools/novidades/gen_cartoes.py",
        "// from src/data/novidades/cartoes.json (tela de novidades do Prof. Carvalho).",
        "//",
        "",
    ]
    topics = data["topics"]
    seen = set()
    for topic in topics:
        tid = topic["id"]
        if not IDENT.fullmatch(tid) or tid in seen:
            raise ValueError(f"id de tópico inválido ou repetido: {tid!r}")
        seen.add(tid)
        if not re.fullmatch(r"ITEM_[A-Z0-9_]+", topic.get("iconItemId", "")):
            raise ValueError(f"{tid}: iconItemId inválido")
        if topic.get("iconCustom", 0) not in (0, 1, 2, 3, 4):
            raise ValueError(f"{tid}: iconCustom fora de 0-4")
        if not topic["cards"]:
            raise ValueError(f"{tid}: tópico sem cartão")
        out.append(f"static const u8 sNovidadesText_{tid}_name[] = _(\"{_c_string(topic['name'], tid)}\");")
        for n, card in enumerate(topic["cards"], 1):
            _check_card(card, f"{tid} #{n}")
            for field in TEXT_FIELDS:
                if card.get(field):
                    out.append(f"static const u8 sNovidadesText_{tid}_{n}_{field}[] = "
                               f"_(\"{_c_string(card[field], f'{tid} #{n} {field}')}\");")
        out += ["", f"static const struct NovidadesCard sNovidadesCards_{tid}[] =", "{"]
        for n, card in enumerate(topic["cards"], 1):
            out.append("    {")
            for field in TEXT_FIELDS:
                if card.get(field):
                    out.append(f"        .{field} = sNovidadesText_{tid}_{n}_{field},")
            for field in ("speciesBefore", "speciesAfter", "itemId"):
                if card.get(field):
                    out.append(f"        .{field} = {card[field]},")
            out.append("    },")
        out += ["};", ""]
    out += ["const struct NovidadesTopic gNovidadesTopics[] =", "{"]
    for topic in topics:
        tid = topic["id"]
        out += ["    {",
                f"        .name = sNovidadesText_{tid}_name,",
                f"        .iconItemId = {topic['iconItemId']},",
                f"        .iconCustom = {topic.get('iconCustom', 0)},",
                f"        .cards = sNovidadesCards_{tid},",
                f"        .cardCount = ARRAY_COUNT(sNovidadesCards_{tid}),",
                "    },"]
    out += ["};", "",
            "STATIC_ASSERT(ARRAY_COUNT(gNovidadesTopics) == NOVIDADES_TOPIC_COUNT, NovidadesTopicCount);",
            ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    Path(argv[2]).write_text(render(argv[1]), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
