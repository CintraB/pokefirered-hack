#!/usr/bin/env python3
"""Hack 8: gera src/data/wild_encounters_leafgreen.h a partir do wild_encounters.json.

Uso (o make chama sozinho): python3 tools/wild_leafgreen/gen_swaps.py <wild_encounters.json> <saída.h>

Para cada tabela `_FireRed` (grama, água, pedra, pesca), compara slot a slot com a `_LeafGreen`
de mesmo nome. Um slot entra na tabela quando a espécie do LeafGreen é diferente e não aparece em
nenhuma tabela `_FireRed` (exclusiva do LeafGreen). No jogo, esse slot sorteia 50%: a linha do
FireRed ou a do LeafGreen (espécie e níveis do LeafGreen). Ver GetLeafGreenSlotMon em
src/wild_encounter.c.

A chave é o ponteiro da WildPokemonInfo do FireRed, então a Caverna Mutante (9 tabelas no mesmo
mapa) e os tipos de encontro se resolvem sozinhos.
"""

import json
import sys
from pathlib import Path

KINDS = (("land_mons", "LandMonsInfo"), ("water_mons", "WaterMonsInfo"),
         ("rock_smash_mons", "RockSmashMonsInfo"), ("fishing_mons", "FishingMonsInfo"))


def compute_swaps(data: dict) -> list[tuple[str, int, dict, str]]:
    """[(símbolo da WildPokemonInfo FR, slot, linha LG, espécie FR)] na ordem do JSON."""
    encs = [e for g in data["wild_encounter_groups"] for e in g["encounters"]]
    fr_species = {m["species"] for e in encs if "FireRed" in e["base_label"]
                  for k, _ in KINDS if k in e for m in e[k]["mons"]}
    by_label = {e["base_label"]: e for e in encs}
    swaps = []
    for fr in encs:
        if "FireRed" not in fr["base_label"]:
            continue
        lg = by_label.get(fr["base_label"].replace("FireRed", "LeafGreen"))
        if lg is None:
            continue
        for kind, suffix in KINDS:
            if kind not in fr or kind not in lg:
                continue
            for slot, (a, b) in enumerate(zip(fr[kind]["mons"], lg[kind]["mons"])):
                if a["species"] != b["species"] and b["species"] not in fr_species:
                    swaps.append((f"{fr['base_label']}_{suffix}", slot, b, a["species"]))
    return swaps


def render(json_path) -> str:
    data = json.loads(Path(json_path).read_text(encoding="utf-8"))
    lines = [
        "//",
        "// DO NOT MODIFY THIS FILE! It is auto-generated by tools/wild_leafgreen/gen_swaps.py",
        "// from src/data/wild_encounters.json (Hack 8: LeafGreen exclusives share the slot 50/50).",
        "//",
        "",
        "#ifdef FIRERED",
        "const struct WildLeafGreenSwap gWildLeafGreenSwaps[] =",
        "{",
    ]
    for info, slot, mon, fr_species in compute_swaps(data):
        lines.append(f"    {{ &{info}, {slot}, {{ {mon['min_level']}, {mon['max_level']}, "
                     f"{mon['species']} }} }}, // {fr_species}")
    lines += [
        "};",
        "",
        "const u16 gWildLeafGreenSwapsCount = ARRAY_COUNT(gWildLeafGreenSwaps);",
        "#endif // FIRERED",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    Path(argv[2]).write_text(render(argv[1]), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
